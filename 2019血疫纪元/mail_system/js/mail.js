// 打开附件查看器
function openAttachment(path, name) {
    const content = attachmentContents[path];
    if (!content) {
        alert('附件内容暂不可用');
        return;
    }

    // 判断是否为Markdown文件
    const isMarkdown = name.endsWith('.md');

    // 渲染内容
    let renderedContent;
    if (isMarkdown && typeof marked !== 'undefined') {
        // 配置marked选项
        marked.setOptions({
            breaks: true,
            gfm: true,
            headerIds: true,
            mangle: false
        });
        renderedContent = marked.parse(content);
    } else {
        renderedContent = `<pre class="attachment-content">${escapeHtml(content)}</pre>`;
    }

    // 创建模态框
    const modal = document.createElement('div');
    modal.className = 'attachment-modal';
    modal.innerHTML = `
        <div class="attachment-modal-content">
            <div class="attachment-modal-header">
                <div class="attachment-modal-title">
                    <span class="attachment-modal-icon">${isMarkdown ? '📝' : '📄'}</span>
                    <span>${name}</span>
                    ${isMarkdown ? '<span class="markdown-badge">Markdown</span>' : ''}
                </div>
                <button class="attachment-modal-close" onclick="closeAttachment()">&times;</button>
            </div>
            <div class="attachment-modal-body ${isMarkdown ? 'markdown-body' : ''}">
                ${renderedContent}
            </div>
        </div>
    `;

    document.body.appendChild(modal);

    // 防止背景滚动
    document.body.style.overflow = 'hidden';

    // 点击背景关闭
    modal.addEventListener('click', function (e) {
        if (e.target === modal) {
            closeAttachment();
        }
    });
}

// 关闭附件查看器
function closeAttachment() {
    const modal = document.querySelector('.attachment-modal');
    if (modal) {
        document.body.removeChild(modal);
        document.body.style.overflow = '';
    }
}

// HTML转义函数
function escapeHtml(text) {
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML;
}