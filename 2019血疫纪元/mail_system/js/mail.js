// 创建邮件列表项
function createMailItem(mail) {
    const item = document.createElement('div');
    item.className = `mail-item ${mail.isRead ? '' : 'unread'} ${currentMailId === mail.id ? 'active' : ''}`;
    item.dataset.mailId = mail.id;

    item.innerHTML = `
        <div class="mail-item-header">
            <span class="mail-sender">${mail.sender.name}</span>
            <span class="mail-time">${formatTime(mail.time)}</span>
        </div>
        <div class="mail-subject">${mail.subject}</div>
        <div class="mail-preview">${mail.preview}</div>
    `;

    item.addEventListener('click', () => {
        selectMail(mail.id);
    });

    return item;
}

// 选中邮件
function selectMail(mailId) {
    const mail = mailData.find(m => m.id === mailId);
    if (!mail) return;

    // 标记为已读
    if (!mail.isRead) {
        mail.isRead = true;
        updateUnreadCount();
    }

    // 更新当前选中的邮件
    currentMailId = mailId;

    // 更新列表项的样式
    document.querySelectorAll('.mail-item').forEach(item => {
        if (parseInt(item.dataset.mailId) === mailId) {
            item.classList.add('active');
            item.classList.remove('unread');
        } else {
            item.classList.remove('active');
        }
    });

    // 显示邮件详情
    showMailDetail(mail);
}

